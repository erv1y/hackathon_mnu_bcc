def pdf_label(value, language):
    if not isinstance(value, str) or language not in {"en", "kk"}:
        return value
    match = re.fullmatch(r"(\d+\. )(.+)", value)
    prefix, key = match.groups() if match else ("", value)
    if key not in LABELS:
        return value
    return prefix + LABELS[key][language == "kk"]
